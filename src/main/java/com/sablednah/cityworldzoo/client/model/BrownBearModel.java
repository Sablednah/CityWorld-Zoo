package com.sablednah.cityworldzoo.client.model;

import com.sablednah.cityworldzoo.entity.BrownBear;
import com.sablednah.cityworldzoo.entity.Stride;

import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;

/**
 * Sable's brown bear (art/brown_bear/brown_bear.bbmodel, 2026-10-13: vanilla's polar bear shape, painted),
 * converted by tools/blockbench/bbmodel_to_java.py: the mesh below and the repacked texture are GENERATED --
 * re-run the converter and install_mesh.py after a Blockbench edit rather than editing numbers here. Drawn
 * at 1.2, as vanilla draws its polar bear. The animation is hand-written: a rolling walk sized to the ground
 * going by ({@link Gait}), the head following the look and swinging a little with the stride. Baby: the
 * whole mesh at half size, one texture.
 */
public class BrownBearModel extends HierarchicalModel<BrownBear> {

    public static final float SCALE = 1.2F;
    private final ModelPart head;
    private final ModelPart[] legs;

    private final ModelPart root;

    public BrownBearModel(ModelPart root) {
        this.root = root;
        this.head = root.getChild("head");
        String[] names = {"left_front", "right_hind", "right_front", "left_hind"}; // diagonal pairs: 0 with 1, 2 with 3
        this.legs = new ModelPart[4];
        for (int i = 0; i < 4; i++) legs[i] = root.getChild(names[i] + "_leg");
    }

    @Override
    public ModelPart root() {
        return root;
    }

    public static LayerDefinition createBodyLayer() {
        return LayerDefinition.create(mesh(), 64, 128);
    }


    // --- generated by tools/blockbench/bbmodel_to_java.py from art/brown_bear/brown_bear.bbmodel ---
    private static MeshDefinition mesh() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition head = root.addOrReplaceChild("head",
                CubeListBuilder.create()
                        .texOffs(0, 85).addBox(-3.5F, -3.0F, -3.0F, 7.0F, 7.0F, 7.0F)
                        .texOffs(29, 85).addBox(-2.5F, 1.0F, -6.0F, 5.0F, 3.0F, 3.0F)
                        .texOffs(46, 85).addBox(2.5F, -4.0F, -1.0F, 2.0F, 2.0F, 1.0F)
                        .texOffs(53, 85).addBox(-4.5F, -4.0F, -1.0F, 2.0F, 2.0F, 1.0F),
                PartPose.offset(0.0F, 10.0F, -16.0F));
        PartDefinition body = root.addOrReplaceChild("body",
                CubeListBuilder.create()
                        .texOffs(0, 0).addBox(-5.0F, -4.0F, -13.0F, 14.0F, 11.0F, 14.0F)
                        .texOffs(0, 26).addBox(-4.0F, -3.0F, -25.0F, 12.0F, 10.0F, 12.0F),
                PartPose.offset(-2.0F, 9.0F, 12.0F));
        PartDefinition lefthindleg = root.addOrReplaceChild("left_hind_leg",
                CubeListBuilder.create()
                        .texOffs(0, 49).addBox(-2.0F, 0.0F, -2.0F, 4.0F, 10.0F, 8.0F),
                PartPose.offset(4.5F, 14.0F, 6.0F));
        PartDefinition righthindleg = root.addOrReplaceChild("right_hind_leg",
                CubeListBuilder.create()
                        .texOffs(25, 49).addBox(-2.0F, 0.0F, -2.0F, 4.0F, 10.0F, 8.0F),
                PartPose.offset(-4.5F, 14.0F, 6.0F));
        PartDefinition leftfrontleg = root.addOrReplaceChild("left_front_leg",
                CubeListBuilder.create()
                        .texOffs(0, 68).addBox(-2.0F, 0.0F, -2.0F, 4.0F, 10.0F, 6.0F),
                PartPose.offset(3.5F, 14.0F, -8.0F));
        PartDefinition rightfrontleg = root.addOrReplaceChild("right_front_leg",
                CubeListBuilder.create()
                        .texOffs(21, 68).addBox(-2.0F, 0.0F, -2.0F, 4.0F, 10.0F, 6.0F),
                PartPose.offset(-3.5F, 14.0F, -8.0F));
        return mesh;
    }
    // --- end generated ---

    @Override
    public void setupAnim(BrownBear entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root.getAllParts().forEach(ModelPart::resetPose);   // 26.2's EntityModel.setupAnim does this
        if (entity.isBaby()) limbSwing /= 3.0F;   // 1.21.1's renderer triples a baby's walk position; 26.2's does not
        limbSwing = entity.walkPosition(limbSwing);   // the species' cadence, applied by the entity on 26.2
        float rad = (float) Math.PI / 180.0F;
        float pos = limbSwing;
        float walking = Gait.ramp(limbSwingAmount);
        this.head.yRot = netHeadYaw * rad + Mth.cos(pos * 0.3331F) * 0.08F * walking;
        this.head.xRot = headPitch * rad;
        // Standing, the head sways slowly side to side and dips to sniff the ground now and then.
        float idle = 1.0F - walking;
        this.head.yRot += Mth.sin(ageInTicks * 0.04F) * 0.3F * idle;
        this.head.xRot += 0.45F * Idle.window(ageInTicks, 0.015F, 0.7F, 0.8F, 0.1F) * idle;
        float amp = Stride.BROWN_BEAR.swing() * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.legs[i].xRot += Mth.cos(phase) * amp;
        }
    }
}
