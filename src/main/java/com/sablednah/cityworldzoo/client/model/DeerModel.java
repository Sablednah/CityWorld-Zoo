    @Override
    public void setupAnim(LivingEntityRenderState state) {
        super.setupAnim(state);
        float rad = (float) Math.PI / 180.0F;
        float pos = state.walkAnimationPos;
        float walking = Gait.ramp(state.walkAnimationSpeed);
        float age = state.ageInTicks;

        // Looking: the neck turns half way, the head the rest and all of the pitch; the head dips with the stride.
        this.neck.yRot = state.yRot * rad * 0.5F;
        this.head.yRot = state.yRot * rad * 0.5F;
        this.head.xRot = state.xRot * rad + Mth.cos(pos * 0.6662F) * 0.05F * walking;

        // Short legs, so a wide swing to keep up with the ground; the knee folds on the forward swing.
        float amp = Stride.DEER.swing() * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.upper[i].xRot += Mth.cos(phase) * amp;
            this.lower[i].xRot += Math.max(0.0F, Mth.sin(phase)) * amp * 0.9F;
        }

        // Grazing: the neck goes down and the head follows; now and then the head snaps up to look around.
        float graze = Idle.window(age, 0.009F, 0.5F, 0.3F, 0.12F) * (1.0F - walking);
        float lookUp = Idle.window(age, 0.06F, 0.0F, 0.9F, 0.05F);
        this.neck.xRot += 1.0F * graze * (1.0F - lookUp);
        this.head.xRot -= 0.35F * graze * (1.0F - lookUp);

        // The tail flicks now and then, and lifts when moving.
        this.tail.zRot = Mth.sin(age * 0.35F) * (Mth.sin(age * 0.021F) > 0.9F ? 0.4F : 0.0F);
        this.tail.xRot = -0.3F - 0.5F * walking;
    }
