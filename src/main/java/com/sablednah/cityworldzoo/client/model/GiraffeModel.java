    @Override
    public void setupAnim(GiraffeRenderState state) {
        super.setupAnim(state);
        float rad = (float) Math.PI / 180.0F;
        float pos = state.walkAnimationPos;
        float speed = state.walkAnimationSpeed;
        float age = state.ageInTicks;

        // Looking: the neck leans a little forward at rest and more on the move, takes half the turn, nods with
        // the stride; the head takes the rest of the turn and the pitch, levelled against the lean.
        this.neck.xRot += NECK_LEAN + 0.08F * Gait.ramp(speed) + Mth.cos(pos * 0.6662F) * 0.04F * Gait.ramp(speed);
        this.neck.yRot = state.yRot * rad * 0.5F;
        this.head.yRot = state.yRot * rad * 0.5F;
        this.head.xRot = -NECK_LEAN + state.xRot * rad;

        // Walking: diagonal pairs swing from the shoulder by the angle that keeps a planted hoof still on the
        // ground (the hip is 30 units up, times the entity's scale); the knee folds as the leg swings forward
        // and the hoof trails it, so the leg reads as three joints rather than a stiff post.
        float amp = Stride.GIRAFFE.swing() * Gait.ramp(speed);
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.upper[i].xRot += Mth.cos(phase) * amp;
            float fold = Math.max(0.0F, Mth.sin(phase)) * amp * 1.3F;
            this.lower[i].xRot += fold;
            this.hoof[i].xRot += -fold * 0.5F;
        }

        // Feeding: the goal has put a leaf block within reach and synced where it is. Bend the neck from its
        // pivot towards it so the neck's tip lands a head's reach short, level the head on the end, and chew.
        if (state.browse != null) {
            Vec3 b = state.browse;
            double yaw = Math.toRadians(state.bodyRot);
            // into the body's frame: forward is -z in the model, +z in the world when the body faces yaw 0
            double fwd = -(b.x * Math.sin(yaw)) + b.z * Math.cos(yaw);
            double side = b.x * Math.cos(yaw) + b.z * Math.sin(yaw);
            double up = b.y - NECK_UP;
            double reach = fwd - NECK_FORWARD - HEAD_LENGTH - 0.5 + BITE;
            float pitch = (float) Mth.clamp(Math.atan2(reach, up), -0.25, 1.35);   // 0 is the neck straight up
            float turn = (float) Mth.clamp(Math.atan2(-side, Math.max(0.3, fwd)), -0.7, 0.7);
            this.neck.xRot = pitch;
            this.neck.yRot = turn;
            this.head.xRot = -pitch + 0.15F + Mth.sin(age * 0.6F) * 0.06F;   // level, a touch down, chewing
            this.head.yRot = turn * 0.3F;
        }

        // Idle: ears twitch on their own clocks, the tail swishes side to side and lifts a little as it walks.
        this.leftEar.zRot += Mth.sin(age * 0.11F) * 0.12F + flick(age, 0.0F);
        this.rightEar.zRot -= Mth.sin(age * 0.13F + 1.7F) * 0.12F + flick(age, 2.9F);
        this.tail.zRot = Mth.sin(age * 0.1F) * 0.3F;
        this.tail.xRot = 0.1F + Gait.ramp(speed) * 0.3F;
    }

    /** A quick ear flick now and then: a short burst riding a slow clock, so the two ears rarely flick together. */
    private static float flick(float age, float offset) {
        float slow = Mth.sin(age * 0.023F + offset);
        return slow > 0.96F ? Mth.sin(age * 1.3F) * 0.35F : 0.0F;
    }
