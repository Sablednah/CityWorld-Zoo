    @Override
    public void setupAnim(Lion entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root.getAllParts().forEach(ModelPart::resetPose);   // 26.2's EntityModel.setupAnim does this
        if (entity.isBaby()) limbSwing /= 3.0F;   // 1.21.1's renderer triples a baby's walk position; 26.2's does not
        limbSwing = entity.walkPosition(limbSwing);   // the species' cadence, applied by the entity on 26.2
        float rad = (float) Math.PI / 180.0F;
        float pos = limbSwing;
        float walking = Gait.ramp(limbSwingAmount);
        float age = ageInTicks;

        this.head.yRot = netHeadYaw * rad;
        this.head.xRot = headPitch * rad + Mth.cos(pos * 0.6662F) * 0.04F * walking;

        // A cat's walk: long low strides from the hip, the knee folding on the forward swing.
        float amp = Stride.LION.swing() * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.upper[i].xRot += Mth.cos(phase) * amp;
            this.lower[i].xRot += Math.max(0.0F, Mth.sin(phase)) * amp * 0.8F;
        }

        // Sitting: body pitched up and lowered onto the haunches, hind legs folded, front legs straight and the
        // head carried up with the raised chest.
        float sit = Idle.window(age, 0.007F, 2.0F, 0.35F, 0.15F) * (1.0F - walking);
        this.body.xRot -= 0.45F * sit;
        this.body.y += 3.0F * sit;
        for (int i : new int[] {1, 3}) {   // the hind legs
            this.upper[i].xRot -= 1.2F * sit;
            this.upper[i].y += 6.0F * sit;
            this.upper[i].z += 2.0F * sit;
            this.lower[i].xRot += 1.6F * sit;
        }
        for (int i : new int[] {0, 2}) this.upper[i].y -= 1.8F * sit;   // the front legs hang from the raised chest
        this.head.xRot += 0.3F * sit;   // the head rides the pitched body; keep the gaze level

        // The tail hangs low, sways with the stride and flicks on its own now and then.
        this.tail.xRot = 0.15F + Mth.cos(pos * 0.3331F) * 0.1F * walking;
        this.tail.zRot = Mth.sin(age * 0.09F) * 0.15F + (Mth.sin(age * 0.019F) > 0.9F ? Mth.sin(age * 0.7F) * 0.3F : 0.0F);
    }
