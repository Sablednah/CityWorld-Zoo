package com.sablednah.cityworldzoo.client.model;

import java.util.Set;

import com.sablednah.cityworldzoo.entity.Stride;

import net.minecraft.client.model.BabyModelTransform;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.util.Mth;

/**
 * A rhesus macaque: a small quadruped with a round head, muzzle and a curling tail. The mesh is GENERATED by
 * tools/blockbench/spec_to_model.py from its "rhesus_macaque" spec (which also paints the placeholder texture
 * and writes blockbench/rhesus_macaque.bbmodel for Sable): change the spec and re-run, do not edit the
 * numbers here. Legs are 3 + 3 with a knee. The animation is hand-written: a quick walk sized to the ground
 * going by ({@link Gait}), head following the look, a tail that curls and sways. Baby: big-headed half size.
 */
public class MacaqueModel extends EntityModel<LivingEntityRenderState> {

    private final ModelPart body;
    private final ModelPart head;
    private final ModelPart tail;
    private final ModelPart tail2;
    private final ModelPart[] upper;
    private final ModelPart[] lower;

    public MacaqueModel(ModelPart root) {
        super(root);
        this.body = root.getChild("body");
        this.head = body.getChild("head");
        this.tail = body.getChild("tail");
        this.tail2 = tail.getChild("tail2");
        String[] legs = {"left_front", "right_hind", "right_front", "left_hind"}; // diagonal pairs: 0 with 1, 2 with 3
        this.upper = new ModelPart[4];
        this.lower = new ModelPart[4];
        for (int i = 0; i < 4; i++) {
            upper[i] = root.getChild(legs[i] + "_leg");
            lower[i] = upper[i].getChild(legs[i] + "_lower");
        }
    }

    public static LayerDefinition createBodyLayer() {
        return LayerDefinition.create(mesh(), 32, 64);
    }

    public static LayerDefinition createBabyLayer() {
        return LayerDefinition.create(mesh(), 32, 64).apply(new BabyModelTransform(Set.of("head")));
    }

    // --- generated by tools/blockbench/spec_to_model.py rhesus_macaque ---
    private static MeshDefinition mesh() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body",
                CubeListBuilder.create()
                        .texOffs(0, 0).addBox(-2.5F, -2.5F, -4.5F, 5.0F, 5.0F, 9.0F),
                PartPose.offset(0.0F, 15.5F, 0.0F));
        PartDefinition head = body.addOrReplaceChild("head",
                CubeListBuilder.create()
                        .texOffs(0, 15).addBox(-2.0F, -4.0F, -3.0F, 4.0F, 4.0F, 4.0F)
                        .texOffs(18, 36).addBox(-1.0F, -2.0F, -4.0F, 2.0F, 2.0F, 1.0F)
                        .texOffs(25, 36).addBox(2.0F, -3.0F, -1.0F, 1.0F, 2.0F, 1.0F)
                        .texOffs(0, 42).addBox(-3.0F, -3.0F, -1.0F, 1.0F, 2.0F, 1.0F),
                PartPose.offset(0.0F, -2.5F, -4.0F));
        PartDefinition leftfrontleg = root.addOrReplaceChild("left_front_leg",
                CubeListBuilder.create()
                        .texOffs(0, 24).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(2.0F, 18.0F, -3.0F));
        PartDefinition leftfrontlower = leftfrontleg.addOrReplaceChild("left_front_lower",
                CubeListBuilder.create()
                        .texOffs(9, 24).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(0.0F, 3.0F, 0.0F));
        PartDefinition rightfrontleg = root.addOrReplaceChild("right_front_leg",
                CubeListBuilder.create()
                        .texOffs(18, 24).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(-2.0F, 18.0F, -3.0F));
        PartDefinition rightfrontlower = rightfrontleg.addOrReplaceChild("right_front_lower",
                CubeListBuilder.create()
                        .texOffs(0, 30).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(0.0F, 3.0F, 0.0F));
        PartDefinition lefthindleg = root.addOrReplaceChild("left_hind_leg",
                CubeListBuilder.create()
                        .texOffs(9, 30).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(2.0F, 18.0F, 3.0F));
        PartDefinition lefthindlower = lefthindleg.addOrReplaceChild("left_hind_lower",
                CubeListBuilder.create()
                        .texOffs(18, 30).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(0.0F, 3.0F, 0.0F));
        PartDefinition righthindleg = root.addOrReplaceChild("right_hind_leg",
                CubeListBuilder.create()
                        .texOffs(0, 36).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(-2.0F, 18.0F, 3.0F));
        PartDefinition righthindlower = righthindleg.addOrReplaceChild("right_hind_lower",
                CubeListBuilder.create()
                        .texOffs(9, 36).addBox(-1.0F, 0.0F, -1.0F, 2.0F, 3.0F, 2.0F),
                PartPose.offset(0.0F, 3.0F, 0.0F));
        PartDefinition tail = body.addOrReplaceChild("tail",
                CubeListBuilder.create()
                        .texOffs(17, 15).addBox(-0.5F, -6.0F, -0.5F, 1.0F, 6.0F, 1.0F),
                PartPose.offsetAndRotation(0.0F, -1.5F, 4.0F, -0.8F, 0.0F, 0.0F));
        PartDefinition tail2 = tail.addOrReplaceChild("tail2",
                CubeListBuilder.create()
                        .texOffs(22, 15).addBox(-0.5F, -6.0F, -0.5F, 1.0F, 6.0F, 1.0F),
                PartPose.offsetAndRotation(0.0F, -6.0F, 0.0F, 0.9F, 0.0F, 0.0F));
        return mesh;
    }
    // --- end generated ---

    @Override
    public void setupAnim(LivingEntityRenderState state) {
        super.setupAnim(state);
        float rad = (float) Math.PI / 180.0F;
        float pos = state.walkAnimationPos;
        float walking = Gait.ramp(state.walkAnimationSpeed);
        float age = state.ageInTicks;
        this.head.yRot = state.yRot * rad;
        this.head.xRot = state.xRot * rad;
        float amp = Stride.RHESUS_MACAQUE.swing() * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.upper[i].xRot += Mth.cos(phase) * amp;
            this.lower[i].xRot += Math.max(0.0F, Mth.sin(phase)) * amp * 0.8F;
        }
        this.tail.zRot = Mth.cos(age * 0.2F) * 0.15F;
        this.tail2.xRot += Mth.cos(age * 0.2F) * 0.2F;

        // Sitting: standing still for a while, it sits up on its haunches -- body pitched up and dropped onto
        // the ground, hind legs folded forward, head up -- and scratches with a front hand now and then.
        float sit = Idle.window(age, 0.008F, 0.0F, 0.3F, 0.15F) * (1.0F - walking);
        this.body.xRot -= 0.9F * sit;
        this.body.y += 3.4F * sit;
        for (int i : new int[] {1, 3}) {   // the hind legs (diagonal order: 1 = right hind, 3 = left hind)
            this.upper[i].xRot -= 1.3F * sit;
            this.upper[i].y += 4.0F * sit;
            this.lower[i].xRot += 1.6F * sit;
        }
        this.head.xRot += 0.6F * sit;   // the body pitched up 0.9 would tip the face at the sky; look ahead instead
        float scratch = Idle.window(age, 0.05F, 1.0F, 0.8F, 0.1F) * sit;
        this.upper[2].xRot += (-0.6F + Mth.sin(age * 1.5F) * 0.3F) * scratch;
        this.lower[2].xRot += 0.9F * scratch;
    }
}
