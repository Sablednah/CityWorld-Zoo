    @Override
    public void setupAnim(LivingEntityRenderState state) {
        super.setupAnim(state);
        float rad = (float) Math.PI / 180.0F;
        float pos = state.walkAnimationPos;
        float walking = Gait.ramp(state.walkAnimationSpeed);
        float age = state.ageInTicks;

        this.head.yRot = state.yRot * rad;
        this.head.xRot = state.xRot * rad + Mth.cos(pos * 0.6662F) * 0.04F * walking;

        // A cat's walk: long low strides from the hip, the knee folding on the forward swing.
        float amp = Gait.swing(16.0F * state.scale) * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.upper[i].xRot += Mth.cos(phase) * amp;
            this.lower[i].xRot += Math.max(0.0F, Mth.sin(phase)) * amp * 0.8F;
        }

        // The tail sways with the stride; its tip curls and twitches on its own.
        this.tail.zRot = Mth.sin(age * 0.08F) * 0.12F + Mth.cos(pos * 0.3331F) * 0.15F * walking;
        this.tailTip.yRot = Mth.sin(age * 0.11F) * 0.35F + (Mth.sin(age * 0.023F) > 0.9F ? Mth.sin(age * 0.8F) * 0.4F : 0.0F);
        this.tailTip.xRot = Mth.cos(age * 0.07F) * 0.15F;
    }
