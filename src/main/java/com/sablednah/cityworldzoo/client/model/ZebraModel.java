import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.util.Mth;

/**
 * Sable's zebra (art/zebra/zebra.bbmodel, 2026-10-13: vanilla's horse shape, painted), converted by
 * tools/blockbench/bbmodel_to_java.py: the mesh below and the repacked texture are GENERATED -- re-run the
 * converter and install_mesh.py after a Blockbench edit rather than editing numbers here. The rig is the
 * horse's: body with the tail on it, head_parts (neck, mane, mouth) with the head on it, four legs. The
 * animation is hand-written after the horse's: a walk sized to the ground going by ({@link Gait}), the
 * neck turning with the look within a horse's range, the head nodding with the stride, a tail that lifts
 * and swishes. Baby: the whole mesh at half size, same texture (vanilla draws its foal from another mesh).
 */
public class ZebraModel extends EntityModel<LivingEntityRenderState> {

    private final ModelPart headParts;
    private final ModelPart head;
    private final ModelPart tail;
    private final ModelPart[] legs;

    public ZebraModel(ModelPart root) {
        super(root);
        this.headParts = root.getChild("head_parts");
        this.head = headParts.getChild("head");
        this.tail = root.getChild("body").getChild("tail");
        String[] names = {"left_front", "right_hind", "right_front", "left_hind"}; // diagonal pairs: 0 with 1, 2 with 3
        this.legs = new ModelPart[4];
        for (int i = 0; i < 4; i++) legs[i] = root.getChild(names[i] + "_leg");
    }

    public static LayerDefinition createBodyLayer() {
        return LayerDefinition.create(mesh(), 64, 128);
    }

    public static LayerDefinition createBabyLayer() {
        return LayerDefinition.create(mesh(), 64, 128).apply(new BabyModelTransform(Set.of()));
    }

    // --- generated by tools/blockbench/bbmodel_to_java.py from art/zebra/zebra.bbmodel ---
    private static MeshDefinition mesh() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body",
                CubeListBuilder.create()
                        .texOffs(0, 0).addBox(-5.0F, -8.0F, -17.0F, 10.0F, 10.0F, 22.0F),
                PartPose.offset(0.0F, 11.0F, 5.0F));
        PartDefinition tail = body.addOrReplaceChild("tail",
                CubeListBuilder.create()
                        .texOffs(23, 33).addBox(-1.5F, 0.0F, 0.0F, 3.0F, 14.0F, 4.0F),
                PartPose.offsetAndRotation(0.0F, -5.0F, 2.0F, 0.524F, 0.0F, 0.0F));
        PartDefinition headparts = root.addOrReplaceChild("head_parts",
                CubeListBuilder.create()
                        .texOffs(0, 33).addBox(-2.05F, -6.0F, -2.0F, 4.0F, 12.0F, 7.0F)
                        .texOffs(38, 33).addBox(-1.0F, -11.0F, 5.01F, 2.0F, 16.0F, 2.0F)
                        .texOffs(27, 70).addBox(-2.0F, -11.0F, -7.0F, 4.0F, 5.0F, 5.0F),
                PartPose.offsetAndRotation(0.0F, 4.0F, -12.0F, 0.524F, 0.0F, 0.0F));
        PartDefinition head = headparts.addOrReplaceChild("head",
                CubeListBuilder.create()
                        .texOffs(0, 70).addBox(-3.0F, -11.0F, -2.0F, 6.0F, 5.0F, 7.0F)
                        .texOffs(46, 70).addBox(0.55F, -13.0F, 4.0F, 2.0F, 3.0F, 1.0F)
                        .texOffs(53, 70).addBox(-2.55F, -13.0F, 4.0F, 2.0F, 3.0F, 1.0F),
                PartPose.offset(0.0F, 0.0F, 0.0F));
        PartDefinition lefthindleg = root.addOrReplaceChild("left_hind_leg",
                CubeListBuilder.create()
                        .texOffs(47, 33).addBox(-3.0F, -1.01F, -1.0F, 4.0F, 11.0F, 4.0F),
                PartPose.offset(4.0F, 14.0F, 7.0F));
        PartDefinition righthindleg = root.addOrReplaceChild("right_hind_leg",
                CubeListBuilder.create()
                        .texOffs(0, 53).addBox(-1.0F, -1.01F, -1.0F, 4.0F, 11.0F, 4.0F),
                PartPose.offset(-4.0F, 14.0F, 7.0F));
        PartDefinition leftfrontleg = root.addOrReplaceChild("left_front_leg",
                CubeListBuilder.create()
                        .texOffs(17, 53).addBox(-3.0F, -1.01F, -1.9F, 4.0F, 11.0F, 4.0F),
                PartPose.offset(4.0F, 14.0F, -10.0F));
        PartDefinition rightfrontleg = root.addOrReplaceChild("right_front_leg",
                CubeListBuilder.create()
                        .texOffs(34, 53).addBox(-1.0F, -1.01F, -1.9F, 4.0F, 11.0F, 4.0F),
                PartPose.offset(-4.0F, 14.0F, -10.0F));
        return mesh;
    }
    // --- end generated ---

    @Override
    public void setupAnim(LivingEntityRenderState state) {
        super.setupAnim(state);
        float rad = (float) Math.PI / 180.0F;
        float pos = state.walkAnimationPos;
        float walking = Gait.ramp(state.walkAnimationSpeed);
        float age = state.ageInTicks;

        // A horse turns its neck only so far; the head takes the pitch and nods with the stride.
        this.headParts.yRot = Mth.clamp(state.yRot, -20.0F, 20.0F) * rad;
        this.headParts.xRot += state.xRot * rad * 0.5F + Mth.cos(pos * 0.8F) * 0.1F * walking;
        this.head.xRot = state.xRot * rad * 0.3F;

        // Legs: straight, as a horse's are drawn, swinging by the angle that keeps a hoof still on the ground.
        float amp = Stride.ZEBRA.swing() * walking;
        for (int i = 0; i < 4; i++) {
            float phase = pos * 0.6662F + (i < 2 ? 0.0F : (float) Math.PI);
            this.legs[i].xRot += Mth.cos(phase) * amp;
        }

        // Grazing: the neck swings down as a horse's does to eat.
        float graze = Idle.window(age, 0.0075F, 3.0F, 0.35F, 0.15F) * (1.0F - walking);
        this.headParts.xRot += 1.2F * graze;

        // The tail lifts as it moves and swishes now and then.
        this.tail.xRot += 0.5F * walking;
        this.tail.yRot = Mth.cos(age * 0.12F) * (Mth.sin(age * 0.017F) > 0.8F ? 0.5F : 0.1F);
    }
}
